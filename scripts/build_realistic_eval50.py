def build_design(records: list[dict]) -> str:
    from collections import Counter

    categories = Counter(row["focus_category"] for row in records)
    dimensions = Counter(row["test_dimension"] for row in records)
    difficulties = Counter(row["difficulty"] for row in records)
    levels = Counter(row["risk_level"] for row in records)
    intents = Counter(row["user_intent"] for row in records)
    lines = [
        "# 真实场景评测集 v1：结构与分布",
        "",
        "- 样本数：50",
        "- 案件族：50（每条一个全新案件族）",
        "- 定位：规则优化开发回归集，不是独立盲测",
        "- 设计原则：不通过替换姓名、金额、平台制造伪新样本；每条采用不同关系、动作链或资金路径。",
        "",
        "## 字段结构",
        "",
        "每条包含用户要求的中文审核字段，并保留 `conversation`、`user_intent`、`fraud_type`、`risk_level`、`current_stage` 等英文机器字段以及现有接口兼容的 `labels`。",
        "",
        "## 类别分布",
        "",
        "| 重点类别 | 数量 |",
        "|---|---:|",
    ]
    lines.extend(f"| {key} | {value} |" for key, value in sorted(categories.items()))
    for title, counter in [("测试维度", dimensions), ("难度", difficulties), ("风险等级", levels), ("用户意图", intents)]:
        lines += ["", f"## {title}分布", "", "| 标签 | 数量 |", "|---|---:|"]
        lines.extend(f"| {key} | {value} |" for key, value in counter.most_common())
    lines += [
        "",
        "## 使用边界",
        "",
        "本批数据在生成后立即用于评估和规则优化，因此从第一次评估开始即属于开发集。后续正式成绩必须使用开发者未见、按案件族隔离并冻结的独立盲测集。",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    if len(CASES) != 50:
        raise ValueError(f"Expected 50 cases, got {len(CASES)}")
    records = [to_record(i, case) for i, case in enumerate(CASES, 1)]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(json.dumps(row, ensure_ascii=False) for row in records) + "\n", encoding="utf-8")
    SCHEMA_OUT.write_text(json.dumps(SCHEMA, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    DESIGN_OUT.write_text(build_design(records), encoding="utf-8")
    print(OUT)
    print(SCHEMA_OUT)
    print(DESIGN_OUT)


if __name__ == "__main__":
    main()
