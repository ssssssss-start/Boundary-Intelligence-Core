def make_advice(record: dict) -> str:
    base = [
        "先暂停转账、扫码、点击链接、下载APP、共享屏幕和继续提交资料。",
        "通过官方APP、官网电话、线下网点、本人视频或熟人原号码进行二次核验。",
        "不要提供短信验证码、支付密码、银行卡号、身份证照片、人脸识别或远程控制权限。",
        "保留聊天记录、来电号码、链接、二维码、APP安装包、收款账户和转账凭证。",
    ]
    if "贷款前收费" in record["tags"]:
        base.append("任何放款前收保证金、解冻费、刷流水、会员费的贷款要求都应停止。")
    if "冒充公检法" in record["tags"]:
        base.append("公检法不会电话办案、不会要求保密转账，也不存在所谓安全账户。")
    if "冒充客服" in record["tags"]:
        base.append("退款、理赔、取消会员只通过官方订单入口或官方客服电话办理。")
    if "无法提现" in record["tags"]:
        base.append("提现失败后继续要求缴费解冻，通常是在扩大损失。")
    return "；".join(base) + "。"


def make_speech(fraud_type: str, stage_name: str, record: dict) -> str:
    if record["risk_level"] == "低风险":
        opening = "现在还没到转账阶段，但已经有可疑信号。"
    elif record["risk_level"] == "中风险":
        opening = "这已经不是普通咨询，风险正在升级。"
    else:
        opening = "这已经是高风险场景，建议立即停止操作。"
    return (
        f"{opening}你遇到的“{record['scene']}”符合{fraud_type}在{stage_name}的常见表现。"
        f"对方的关键动作是：{record['request']}。不要继续转账、点链接、给验证码或共享屏幕，"
        "先通过官方渠道或当面核实；如果已经付款，马上联系银行止付并报警。"
    )


def build_title(fraud_type: str, stage_name: str, record: dict, knowledge_type: str) -> str:
    label = {
        "fraud_type": "识别口径",
        "process": "阶段流程",
        "case": "匿名案例",
        "advice": "处置建议",
        "speech": "劝阻话术",
    }[knowledge_type]
    return f"{fraud_type}｜{stage_name}｜{record['scene']}｜{label}"


def build_content(fraud: dict, stage_name: str, record: dict, knowledge_type: str) -> str:
    if knowledge_type == "fraud_type":
        return (
            f"{fraud['fraud_type']}的基本识别口径是：{fraud['summary']} "
            f"在“{record['scene']}”中，用户状态是：{record['user_state']} "
            f"常见接触方式是：{record['contact']} 诱导话术是：{record['lure']} "
            f"当前风险等级为{record['risk_level']}，主要原因是：{record['danger']}"
        )
    if knowledge_type == "process":
        return (
            f"{stage_name}的风险链路可以概括为：接触入口：{record['contact']}；"
            f"诱导方式：{record['lure']}；关键要求：{record['request']}；"
            f"危险后果：{record['danger']}。判断时不要只看对方身份包装，而要看是否出现转账、验证码、"
            "屏幕共享、陌生平台入金、无法提现等实质风险动作。"
        )
    if knowledge_type == "case":
        return (
            f"匿名案例：某用户遇到“{record['scene']}”。起初，{record['contact']}，"
            f"随后对方通过“{record['lure']}”取得信任。进入下一步后，对方提出：{record['request']}。"
            f"如果用户继续按指令操作，可能出现的结果是：{record['danger']}。"
            f"该案例对应{stage_name}，风险等级为{record['risk_level']}。"
        )
    if knowledge_type == "advice":
        return (
            f"针对“{record['scene']}”，当前应按{record['risk_level']}处置。"
            f"重点核验点是：{record['check']} {make_advice(record)}"
        )
    if knowledge_type == "speech":
        return make_speech(fraud["fraud_type"], stage_name, record)
    raise ValueError(f"Unsupported knowledge type: {knowledge_type}")


def build_records() -> list[dict]:
    records = []
    for fraud in FRAUDS:
        if len(fraud["stages"]) != 4:
            raise RuntimeError(f"{fraud['fraud_type']} must have 4 stages")
        for stage_index, ((stage_code, stage_name, risk_level), stage) in enumerate(zip(BASE_STAGE_LEVELS, fraud["stages"]), start=1):
            stage = dict(stage)
            stage["risk_level"] = risk_level
            advice = make_advice(stage)
            speech = make_speech(fraud["fraud_type"], stage_name, stage)
            for knowledge_type in KNOWLEDGE_TYPES:
                records.append(
                    {
                        "knowledge_id": f"{fraud['prefix']}_{stage_index:02d}_{stage_code}_{TYPE_CODES[knowledge_type]}",
                        "knowledge_type": knowledge_type,
                        "fraud_type": fraud["fraud_type"],
                        "title": build_title(fraud["fraud_type"], stage_name, stage, knowledge_type),
                        "content": build_content(fraud, stage_name, stage, knowledge_type),
                        "risk_tags": stage["tags"],
                        "risk_level": risk_level,
                        "advice": advice,
                        "speech": speech,
                        "source": SOURCE,
                    }
                )
    return records


def main() -> None:
    records = build_records()
    expected_count = len(FRAUDS) * len(BASE_STAGE_LEVELS) * len(KNOWLEDGE_TYPES)
    if len(records) != expected_count:
        raise RuntimeError(f"Expected {expected_count} records, got {len(records)}")

    ids = [item["knowledge_id"] for item in records]
    duplicate_ids = sorted({item for item in ids if ids.count(item) > 1})
    if duplicate_ids:
        raise RuntimeError(f"Duplicate knowledge_id: {duplicate_ids}")

    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_PATH.write_text(json.dumps(records, ensure_ascii=False, indent=2), encoding="utf-8")

    level_count = {}
    for record in records:
        level_count[record["risk_level"]] = level_count.get(record["risk_level"], 0) + 1
    print(f"Generated {len(records)} records: {OUTPUT_PATH}")
    print(f"Risk level distribution: {level_count}")


if __name__ == "__main__":
    main()
